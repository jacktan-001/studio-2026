// Seed music data for Jack Wave. In the old system this lived behind a Cloudflare
// KV-backed admin API (moodPlaylists / monthlyShares / allTags). For now we ship a
// static seed so the player has a real, playable catalogue; the data layer is
// structured to be swapped for the live API (see studio-2026-audit.md → backend).
//
// NOTE: we only have one synthesized ambient bed in /public/audio, so every track
// points at /audio/ambient.wav as a placeholder. Replace `src` with real files
// (or wire the backend) when assets are available.

export interface Track {
  id: string
  title: string
  artist: string
  src: string
  duration: string
  appleTrackId?: string | number | null
  applePreviewUrl?: string | null
  appleArtworkUrl?: string | null
  /** Apple Music web page for this track — powers the player's jump button. */
  appleMusicUrl?: string | null
  durationMs?: number | null
}

export interface MoodPlaylist {
  id: string
  title: string
  mood: string
  date: string
  note: string
  songList: Track[]
}

export const SRC = '/audio/ambient.wav'

function tracks(issue: string, list: [string, string, string][]): Track[] {
  return list.map(([title, artist, duration], i) => ({
    id: `${issue}-${i + 1}`,
    title,
    artist,
    duration,
    src: SRC,
  }))
}

/**
 * 优先从线上 /api/public-data 拉取歌单（后台可编辑）；
 * 后端不可用或返回空时回退到本文件静态种子，保证播放器永远有内容。
 */
export async function fetchPlaylists(): Promise<MoodPlaylist[]> {
  try {
    const res = await fetch('/api/public-data', { headers: { Accept: 'application/json' } })
    if (res.ok) {
      const json = await res.json()
      const remote = json?.data?.moodPlaylists
      if (Array.isArray(remote) && remote.length > 0) {
        return remote.map(normalizePlaylist)
      }
    }
  } catch {
    /* 离线 / 后端未就绪 → 回退静态种子 */
  }
  return MOOD_PLAYLISTS
}

function normalizePlaylist(raw: any, i: number): MoodPlaylist {
  const id = raw?.id ?? String(i + 1).padStart(2, '0')
  return {
    id,
    title: raw?.title ?? '未命名歌单',
    mood: raw?.mood ?? '',
    date: raw?.date ?? '',
    note: raw?.note ?? '',
    songList: Array.isArray(raw?.songList)
      ? raw.songList.map((s: any, j: number) => ({
          id: s?.id ?? `${id}-${j + 1}`,
          title: s?.title ?? 'Untitled',
          artist: s?.artist ?? '',
          duration: s?.duration ?? '',
          src: s?.src ?? SRC,
          appleTrackId: s?.appleTrackId ?? null,
          applePreviewUrl: s?.applePreviewUrl ?? '',
          appleArtworkUrl: s?.appleArtworkUrl ?? '',
          appleMusicUrl: s?.appleMusicUrl ?? '',
          durationMs: s?.durationMs ?? null,
        }))
      : [],
  }
}

